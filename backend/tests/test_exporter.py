# ---------------------------------------------------------------------------
# 3. Full-grid left table: every catalog row emitted, nothing spills past
# ---------------------------------------------------------------------------


def test_left_table_full_grid(workbook_bytes, grids, sheet_cases):
    assert len(grids["produk"]) == _GRID_SIZES["produk"]
    assert len(grids["produk2"]) == _GRID_SIZES["produk2"]

    wb = _load(workbook_bytes)
    for title, _key, grid, group_order in sheet_cases:
        ws = wb[title]
        emitted = _emission_rows(grid, group_order)
        assert len(emitted) == len(grid), title
        for i, (group, variant) in enumerate(emitted):
            row = 2 + i
            expected_group = group if (i == 0 or emitted[i - 1][0] != group) else None
            assert ws.cell(row=row, column=1).value == expected_group, (
                f"{title}!A{row}"
            )
            assert ws.cell(row=row, column=2).value == variant, f"{title}!B{row}"
            # E contribution formula present on every left-table row.
            assert isinstance(ws.cell(row=row, column=5).value, str), f"{title}!E{row}"
        # Nothing may spill past the last grid row.
        assert ws.cell(row=2 + len(grid), column=2).value is None, title


