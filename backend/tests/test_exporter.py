def _load(workbook_bytes):
    """Reloads the generated workbook bytes (a seekable BytesIO)."""
    workbook_bytes.seek(0)
    return openpyxl.load_workbook(workbook_bytes, data_only=False)


def _cell_int(ws, row: int, col: int) -> int:
    """Reads an integer cell value (non-int cells/empties read as 0)."""
    value = ws.cell(row=row, column=col).value
    return value if isinstance(value, int) else 0


def _emission_rows(grid, group_order):
    """(group, variant) sequence exactly as render_side_by_side_sheet emits.

    Mirrors the renderer's two-loop emission order: for each canonical group,
    every matching catalog grid row.
    """
    rows: list[tuple[str, str]] = []
    for group in group_order:
        group_key = group.rstrip()
        for gr in grid:
            if gr.product_group.rstrip() == group_key:
                rows.append((group_key, gr.clean_variant.rstrip()))
    return rows


def _group_spans(grid, group_order) -> dict[str, tuple[int, int]]:
    """{group: (start_row, end_row)} laid out in the rendered left table."""
    spans: dict[str, list[int]] = {}
    for i, (group, _variant) in enumerate(_emission_rows(grid, group_order)):
        row = 2 + i
        if group not in spans:
            spans[group] = [row, row]
        else:
            spans[group][1] = row
    return {group: tuple(span) for group, span in spans.items()}


def _sold_keys(populated) -> set[tuple[str, str]]:
    """(group, variant) keys that actually sold (qty > 0)."""
    return {
        (row["product_group"].rstrip(), row["clean_variant"].rstrip())
        for row in populated
        if int(row["total_qty"]) > 0
    }


def _group_emitted_sum(ws, group_order, group):
    """Sums the C/D values covered by a populated group's H/I =SUM ranges."""
    summary_row = 2 + group_order.index(group)
    h = ws.cell(row=summary_row, column=8).value
    i = ws.cell(row=summary_row, column=9).value
    m_h = _SUM_RE.match(h)
    m_i = _SUM_RE.match(i)
    assert m_h and m_i, f"expected SUM formulas for {group}, got H={h!r} I={i!r}"
    assert m_h.group(1) == m_h.group(3) == "C"
    assert m_i.group(1) == m_i.group(3) == "D"
    start = int(m_h.group(2))
    end = int(m_h.group(4))
    assert (int(m_i.group(2)), int(m_i.group(4))) == (start, end)
    qty = sum(_cell_int(ws, r, 3) for r in range(start, end + 1))
    rev = sum(_cell_int(ws, r, 4) for r in range(start, end + 1))
    return qty, rev


