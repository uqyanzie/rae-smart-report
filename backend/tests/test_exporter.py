# ---------------------------------------------------------------------------
# 5. Dynamic formulas reference valid, in-bounds row ranges
# ---------------------------------------------------------------------------


def test_formula_ranges_in_bounds(workbook_bytes):
    wb = _load(workbook_bytes)
    for title, group_order in SHEET_CASES:
        ws = wb[title]
        grand_total_row = 2 + len(group_order)
        last_summary_row = grand_total_row - 1

        # Left-table extent = last row carrying a value in cols A-E.
        max_left_row: int = 1
        for row in ws.iter_rows(min_col=1, max_col=5):
            if any(cell.value is not None for cell in row):
                max_left_row = max(max_left_row, row[0].row or 0)

        for row in ws.iter_rows():
            for cell in row:
                value = cell.value
                if not isinstance(value, str) or not value.startswith("="):
                    continue
                if value.startswith("=SUM("):
                    m = _SUM_RE.match(value)
                    assert m, f"{title}!{cell.coordinate}: malformed SUM {value!r}"
                    col1, r1, col2, r2 = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
                    assert col1 == col2, f"{title}!{cell.coordinate}: mixed columns {value!r}"
                    if cell.column in (8, 9) and cell.row == grand_total_row:
                        # Grand-total SUM ranges cover the summary rows only.
                        assert (col1, r1, r2) == (get_column_letter(cell.column), 2, last_summary_row), (
                            f"{title}!{cell.coordinate}: {value!r}"
                        )
                    else:
                        # Group SUM ranges must lie inside the emitted left table.
                        assert 2 <= r1 <= r2 <= max_left_row, (
                            f"{title}!{cell.coordinate}: out-of-bounds {value!r}"
                        )
                for anchor in _ANCHOR_RE.findall(value):
                    assert 2 <= int(anchor) <= grand_total_row, (
                        f"{title}!{cell.coordinate}: anchor out of bounds {value!r}"
                    )


# ---------------------------------------------------------------------------
# 6. Produk 2 Group 9 is strictly 36 rows (no double-counting overrun)
# ---------------------------------------------------------------------------


def test_produk2_group9_is_36_rows_not_72():
    grid9 = [
        row
        for row in generate_full_produk2_grid()
        if row.product_group.rstrip() == PRODUK2_GROUP_ORDER[8]
    ]
    assert len(grid9) == 36  # Swipe To Glow (6) x The Bloom (6)

    synthetic = [
        {
            "product_group": row.product_group,
            "clean_variant": row.clean_variant,
            "total_qty": 1,
            "total_revenue": 1_000,
        }
        for row in grid9
    ]

    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Produk 2 S"
    render_side_by_side_sheet(
        ws,
        populated=synthetic,
        grid=grid9,
        group_order=PRODUK2_GROUP_ORDER,
    )

    emitted = sum(
        1
        for r in range(2, 2 + len(grid9))
        if ws.cell(row=r, column=3).value is not None
    )
    assert emitted == 36
    # Nothing may spill past the 36 rows.
    assert ws.cell(row=2 + len(grid9), column=3).value is None

    # Group 9's summary H formula covers exactly C2:C37 (36 rows, not 72).
    summary_row = 2 + PRODUK2_GROUP_ORDER.index(PRODUK2_GROUP_ORDER[8])
    assert ws.cell(row=summary_row, column=8).value == "=SUM(C2:C37)"
    assert ws.cell(row=summary_row, column=9).value == "=SUM(D2:D37)"

    # Every other group stays empty -> literal 0 on the right table.
    assert ws.cell(row=2, column=8).value == 0
    assert ws.cell(row=2, column=9).value == 0


