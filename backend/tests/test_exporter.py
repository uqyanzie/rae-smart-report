def _load(workbook_bytes):
    """Reloads the generated workbook bytes (a seekable BytesIO)."""
    workbook_bytes.seek(0)
    return openpyxl.load_workbook(workbook_bytes, data_only=False)


def _populated_by_title(populated: Dict[str, Sequence[Dict[str, Any]]], title: str):
    key = {
        "Produk S": "produk_s",
        "Produk T": "produk_t",
        "Produk 2 S": "produk2_s",
        "Produk 2 T": "produk2_t",
    }[title]
    return populated[key]


def _cell_int(ws, row: int, col: int) -> int:
    """Reads an integer cell value (non-int cells/empties read as 0)."""
    value = ws.cell(row=row, column=col).value
    return value if isinstance(value, int) else 0


def _group_emitted_sum(ws, group_order, group):
    """Sums the C/D values covered by a populated group's H/I =SUM ranges."""
    summary_row = 2 + group_order.index(group)
    h = ws.cell(row=summary_row, column=8).value
    i = ws.cell(row=summary_row, column=9).value
    m_h = _SUM_RE.match(h)
    m_i = _SUM_RE.match(i)
    assert m_h and m_i, f"expected SUM formulas for {group}, got H={h!r} I={i!r}"
    assert m_h.group(1) == m_h.group(3) == "C"
    assert m_i.group(1) == m_i.group(3) == "D"
    start = int(m_h.group(2))
    end = int(m_h.group(4))
    assert (int(m_i.group(2)), int(m_i.group(4))) == (start, end)
    qty = sum(_cell_int(ws, r, 3) for r in range(start, end + 1))
    rev = sum(_cell_int(ws, r, 4) for r in range(start, end + 1))
    return qty, rev


