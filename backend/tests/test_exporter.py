def test_contribution_anchors_target_formula_cells(workbook_bytes):
    wb = _load(workbook_bytes)
    for title, group_order in SHEET_CASES:
        ws = wb[title]
        grand_total_row = 2 + len(group_order)

        # E (variant contribution): anchor must be the group's H SUM formula.
        for row in ws.iter_rows(min_col=5, max_col=5):
            cell = row[0]
            value = cell.value
            if not isinstance(value, str) or not value.startswith("=("):
                continue
            anchors = _ANCHOR_RE.findall(value)
            assert len(anchors) == 1, f"{title}!{cell.coordinate}: {value!r}"
            anchor = ws.cell(row=int(anchors[0]), column=8).value
            assert isinstance(anchor, str) and anchor.startswith("=SUM("), (
                f"{title}!{cell.coordinate}: E divisor {anchor!r} is not a formula"
            )

        # J (group contribution): anchor must be the grand-total H formula.
        for row in ws.iter_rows(min_col=10, max_col=10):
            cell = row[0]
            value = cell.value
            if not isinstance(value, str) or not value.startswith("=("):
                continue
            anchors = _ANCHOR_RE.findall(value)
            assert len(anchors) == 1 and int(anchors[0]) == grand_total_row, (
                f"{title}!{cell.coordinate}: {value!r}"
            )
            anchor = ws.cell(row=grand_total_row, column=8).value
            assert isinstance(anchor, str) and anchor.startswith("=SUM(H2:"), (
                f"{title}!{cell.coordinate}: J divisor {anchor!r} is not the grand total"
            )


# ---------------------------------------------------------------------------
# 8. Golden total conservation through the emitted left table
# ---------------------------------------------------------------------------


def test_golden_totals_conserved(workbook_bytes):
    wb = _load(workbook_bytes)
    ws_s = wb["Produk S"]
    ws_t = wb["Produk T"]

    qty_s = sum(_cell_int(ws_s, r, 3) for r in range(2, ws_s.max_row + 1))
    rev_s = sum(_cell_int(ws_s, r, 4) for r in range(2, ws_s.max_row + 1))
    assert (qty_s, rev_s) == (GOLDEN_SHOPEE_QTY, GOLDEN_SHOPEE_REVENUE)

    qty_t = sum(_cell_int(ws_t, r, 3) for r in range(2, ws_t.max_row + 1))
    rev_t = sum(_cell_int(ws_t, r, 4) for r in range(2, ws_t.max_row + 1))
    assert (qty_t, rev_t) == (GOLDEN_TIKTOK_QTY, GOLDEN_TIKTOK_REVENUE)

    # Glow Up Tint: formula-range sums over the emitted rows match the golden.
    assert _group_emitted_sum(ws_s, PRODUK_GROUP_ORDER, "Glow Up Tint") == GOLDEN_SHOPEE_GUT
    assert _group_emitted_sum(ws_t, PRODUK_GROUP_ORDER, "Glow Up Tint") == GOLDEN_TIKTOK_GUT


