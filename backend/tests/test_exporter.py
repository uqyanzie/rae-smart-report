# 9. Number formatting masks applied to all numeric cells
# ---------------------------------------------------------------------------


def test_number_formats(workbook_bytes):
    wb = _load(workbook_bytes)
    ws = wb["Produk S"]

    # Left table: C -> INTEGER, D -> CURRENCY, E -> PERCENTAGE (where present).
    for r in range(2, ws.max_row + 1):
        c = ws.cell(row=r, column=3)
        if c.value is not None:
            assert c.number_format == FORMAT_INTEGER, f"Produk S!C{r}"
        d = ws.cell(row=r, column=4)
        if d.value is not None:
            assert d.number_format == FORMAT_CURRENCY_IDR, f"Produk S!D{r}"
        e = ws.cell(row=r, column=5)
        if e.value is not None:
            assert e.number_format == FORMAT_PERCENTAGE, f"Produk S!E{r}"

    # Right table incl. grand total: H -> INTEGER, I -> CURRENCY, J -> PERCENTAGE.
    for r in range(2, 2 + len(PRODUK_GROUP_ORDER) + 1):
        h = ws.cell(row=r, column=8)
        if h.value is not None:
            assert h.number_format == FORMAT_INTEGER, f"Produk S!H{r}"
        i = ws.cell(row=r, column=9)
        if i.value is not None:
            assert i.number_format == FORMAT_CURRENCY_IDR, f"Produk S!I{r}"
        j = ws.cell(row=r, column=10)
        if j.value is not None:
            assert j.number_format == FORMAT_PERCENTAGE, f"Produk S!J{r}"

    # Spot-check the other three sheets' first summary row.
    for title in ("Produk T", "Produk 2 S", "Produk 2 T"):
        ws2 = wb[title]
        assert ws2.cell(row=2, column=8).number_format == FORMAT_INTEGER
        assert ws2.cell(row=2, column=9).number_format == FORMAT_CURRENCY_IDR
        assert ws2.cell(row=2, column=10).number_format == FORMAT_PERCENTAGE
