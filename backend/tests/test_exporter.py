def test_unsold_variants_blank_cd(workbook_bytes, populated, sheet_cases):
    wb = _load(workbook_bytes)
    for title, key, grid, group_order in sheet_cases:
        ws = wb[title]
        sold = _sold_keys(populated[key])
        for i, (group, variant) in enumerate(_emission_rows(grid, group_order)):
            row = 2 + i
            if (group, variant) in sold:
                c = ws.cell(row=row, column=3).value
                d = ws.cell(row=row, column=4).value
                assert isinstance(c, int) and c > 0, f"{title}!C{row}"
                assert isinstance(d, int) and d > 0, f"{title}!D{row}"
            else:
                assert ws.cell(row=row, column=3).value is None, f"{title}!C{row}"
                assert ws.cell(row=row, column=4).value is None, f"{title}!D{row}"


# ---------------------------------------------------------------------------
# 5. Always-on SUM ranges: every group's H/I covers its full contiguous span
# ---------------------------------------------------------------------------


def test_every_group_has_sum_over_span(workbook_bytes, sheet_cases):
    wb = _load(workbook_bytes)
    for title, _key, grid, group_order in sheet_cases:
        ws = wb[title]
        grand_total_row = 2 + len(group_order)
        last_summary_row = grand_total_row - 1
        spans = _group_spans(grid, group_order)
        assert set(spans) == {group.rstrip() for group in group_order}, title

        previous_end: int | None = None
        for group in group_order:
            group_key = group.rstrip()
            summary_row = 2 + group_order.index(group)
            start, end = spans[group_key]
            if previous_end is not None:
                assert start == previous_end + 1, (
                    f"{title} {group_key}: span not contiguous"
                )
            previous_end = end
            assert ws.cell(row=summary_row, column=8).value == f"=SUM(C{start}:C{end})", (
                f"{title}!H{summary_row}"
            )
            assert ws.cell(row=summary_row, column=9).value == f"=SUM(D{start}:D{end})", (
                f"{title}!I{summary_row}"
            )
            assert ws.cell(row=summary_row, column=10).value == (
                f"=(H{summary_row}/$H${grand_total_row})*100%"
            ), f"{title}!J{summary_row}"

        assert ws.cell(row=grand_total_row, column=8).value == (
            f"=SUM(H2:H{last_summary_row})"
        )
        assert ws.cell(row=grand_total_row, column=9).value == (
            f"=SUM(I2:I{last_summary_row})"
        )


# ---------------------------------------------------------------------------
# 6. Zero-total groups: unguarded E formulas (golden #DIV/0! cell pattern)
# ---------------------------------------------------------------------------


def test_zero_total_groups_unguarded_e(workbook_bytes, populated, sheet_cases):
    wb = _load(workbook_bytes)
    for title, key, grid, group_order in sheet_cases:
        ws = wb[title]
        sold_groups = {group for group, _variant in _sold_keys(populated[key])}
        spans = _group_spans(grid, group_order)
        for group in group_order:
            group_key = group.rstrip()
            summary_row = 2 + group_order.index(group)
            h = ws.cell(row=summary_row, column=8).value
            assert isinstance(h, str) and h.startswith("=SUM("), (
                f"{title} {group_key}: H={h!r} must be a SUM formula"
            )
            if group_key in sold_groups:
                continue
            start, end = spans[group_key]
            for r in range(start, end + 1):
                e = ws.cell(row=r, column=5).value
                assert e == f"=(C{r}/$H${summary_row})*100%", (
                    f"{title} {group_key}!E{r}: expected unguarded formula, got {e!r}"
                )


def test_no_baked_div_zero_string(workbook_bytes):
    """No literal `#DIV/0!` value is written; errors are computed on open."""
    wb = _load(workbook_bytes)
    for title in wb.sheetnames:
        ws = wb[title]
        for row in ws.iter_rows():
            for cell in row:
                assert cell.value != "#DIV/0!", f"{title}!{cell.coordinate}"


# ---------------------------------------------------------------------------
# 7. Contribution anchors point at formula cells
# ---------------------------------------------------------------------------


def test_contribution_anchors_target_formula_cells(workbook_bytes, sheet_cases):
    wb = _load(workbook_bytes)
    for title, _key, grid, group_order in sheet_cases:
        ws = wb[title]
        grand_total_row = 2 + len(group_order)

        # E (variant contribution): anchor must be the group's H SUM formula.
        for row in ws.iter_rows(min_col=5, max_col=5):
            cell = row[0]
            value = cell.value
            if not isinstance(value, str) or not value.startswith("=("):
                continue
            anchors = _ANCHOR_RE.findall(value)
            assert len(anchors) == 1, f"{title}!{cell.coordinate}: {value!r}"
            anchor = ws.cell(row=int(anchors[0]), column=8).value
            assert isinstance(anchor, str) and anchor.startswith("=SUM("), (
                f"{title}!{cell.coordinate}: E divisor {anchor!r} is not a formula"
            )

        # J (group contribution): anchor must be the grand-total H formula.
        for row in ws.iter_rows(min_col=10, max_col=10):
            cell = row[0]
            value = cell.value
            if not isinstance(value, str) or not value.startswith("=("):
                continue
            anchors = _ANCHOR_RE.findall(value)
            assert len(anchors) == 1 and int(anchors[0]) == grand_total_row, (
                f"{title}!{cell.coordinate}: {value!r}"
            )
            anchor = ws.cell(row=grand_total_row, column=8).value
            assert isinstance(anchor, str) and anchor.startswith("=SUM(H2:"), (
                f"{title}!{cell.coordinate}: J divisor {anchor!r} is not the grand total"
            )


# ---------------------------------------------------------------------------
# 8. Produk 2 Group 9 is strictly 36 rows (no double-counting overrun)
# ---------------------------------------------------------------------------


def test_produk2_group9_is_36_rows_not_72(grids):
    group9 = PRODUK2_GROUP_ORDER[8]
    full_grid = grids["produk2"]
    g9_rows = [row for row in full_grid if row.product_group.rstrip() == group9]
    assert len(g9_rows) == 36  # Swipe To Glow (6) x The Bloom (6)
    assert len({row.clean_variant for row in g9_rows}) == 36

    synthetic = [
        {
            "product_group": row.product_group,
            "clean_variant": row.clean_variant,
            "total_qty": 1 if row.product_group.rstrip() == group9 else 0,
            "total_revenue": 1_000 if row.product_group.rstrip() == group9 else 0,
        }
        for row in full_grid
    ]

    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Produk 2 S"
    render_side_by_side_sheet(
        ws,
        populated=synthetic,
        grid=full_grid,
        group_order=PRODUK2_GROUP_ORDER,
    )

    spans = _group_spans(full_grid, PRODUK2_GROUP_ORDER)
    start, end = spans[group9]
    assert end - start + 1 == 36

    summary_row = 2 + PRODUK2_GROUP_ORDER.index(group9)
    assert ws.cell(row=summary_row, column=8).value == f"=SUM(C{start}:C{end})"
    assert ws.cell(row=summary_row, column=9).value == f"=SUM(D{start}:D{end})"

    sold_in_span = sum(
        1 for r in range(start, end + 1) if ws.cell(row=r, column=3).value is not None
    )
    assert sold_in_span == 36
    assert ws.cell(row=end + 1, column=3).value is None


